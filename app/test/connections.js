const assert = require('assert');
const { newProject } = require('../js/core.js');
const C = require('../js/connections.js');
(async () => {
  const p = newProject(), h = p.hardware;
  p.method.kind = 'fixed'; p.method.fixed.excitation = 'dc';
  Object.assign(h.magnet, { rotator: 'OWISPS10', rotator_addr: 'COM3', encoder: 'NI9361', encoder_addr: 'cDAQ1Mod1/ctr0', host: '192.168.1.100' });
  Object.assign(h.source, { model: 'K6220', address: 'GPIB0::13::INSTR' });
  Object.assign(h.measure, { volt: 'K2182', volt_addr: 'GPIB0::7::INSTR' });
  assert.deepStrictEqual(C.connectionErrors(p), []);
  assert(!C.selectedDevices(p).some(d => d.role === 'temperature'));
  assert(!(await C.checkDevices(p)).ok, 'missing real backend must fail');
  assert(!(await C.checkDevices(p, { checkDevice: async () => ({ ok: true }) })).ok, 'identity is required');
  assert(!(await C.checkDevices(p, { checkDevice: async () => { throw Error('offline'); } })).ok);
  assert((await C.checkDevices(p, { checkDevice: async d => ({ ok: true, identity: d.model }) })).ok);
  h.backend = 'simulation'; assert((await C.checkDevices(p)).simulated);
  h.measure.volt_addr = h.source.address; assert(C.connectionErrors(p).some(e => /share/.test(e)));
  h.measure.dc_mode = 'delta'; assert.deepStrictEqual(C.connectionErrors(p), []);
  assert.strictEqual(C.selectedDevices(p).find(d => d.role === 'voltmeter').parent, 'source');
  p.method.fixed.excitation = 'delta'; h.measure.volt_addr = '';
  assert.deepStrictEqual(C.connectionErrors(p), []);
  assert.strictEqual(C.selectedDevices(p).find(d => d.role === 'voltmeter').sourceModel, 'K6220');
  h.source.model = 'LS155'; assert(C.connectionErrors(p).some(e => /6220/.test(e)));
  h.source.model = 'K6220'; h.temperature = 'read';
  assert(C.selectedDevices(p).some(d => d.role === 'temperature'));
  h.magnet.host = '';
  assert.deepStrictEqual(C.connectionErrors(p), []);
  assert.strictEqual((await C.checkDevices(p)).positionSource, 'owis', 'unconfigured cDAQ falls back to motor angle');
  h.magnet.host = '192.168.1.100';
  p.method.kind = 'rotating'; h.source.model = 'K6221';
  assert(C.connectionErrors(p).some(e => /lock-in/.test(e)));
  Object.assign(h.measure, { lockin1: 'SR830', lockin1_addr: 'GPIB0::8::INSTR' });
  assert.deepStrictEqual(C.connectionErrors(p), []);
  p.method.rotating.excitation = 'ac';
  Object.assign(h.source, { model: 'MFLI', address: 'dev1234' });
  Object.assign(h.measure, { lockin1: 'MFLI', lockin1_addr: 'dev1234' });
  assert.deepStrictEqual(C.connectionErrors(p), [], 'MFLI source and Lock-in 1 can share the same LabOne device ID');
  Object.assign(h.source, { model: 'K6221', address: 'GPIB0::13::INSTR' });
  Object.assign(h.measure, { lockin1: 'SR830', lockin1_addr: 'GPIB0::8::INSTR' });
  p.method.rotating.excitation = 'dc';
  h.backend = 'real';
  let requests = [];
  const encoderOffline = { checkDevice: async d => {
    requests.push(d);
    if (d.positionSource === 'optical') throw Error('cDAQ or optical encoder offline');
    return { ok: true, identity: d.model };
  } };
  let result = await C.checkDevices(p, encoderOffline);
  assert(result.ok && result.positionSource === 'owis');
  assert(result.results.some(r => r.warning && /Falling back/.test(r.message)));
  assert(requests.some(d => d.positionSource === 'owis' && d.angleType === 'absolute' && d.parent === 'motion'));
  result = await C.checkDevices(p, { checkDevice: async d => ({ ok: true, identity: d.model }) });
  assert(result.ok && result.positionSource === 'optical');
  result = await C.checkDevices(p, { checkDevice: async d => {
    if (d.role === 'position') throw Error('No angle readback');
    return { ok: true, identity: d.model };
  } });
  assert(!result.ok && result.positionSource === null, 'failed motor fallback must block progression');
  h.magnet.encoder = ''; h.magnet.host = ''; h.magnet.encoder_addr = '';
  requests = [];
  result = await C.checkDevices(p, encoderOffline);
  assert(result.ok && result.positionSource === 'owis');
  assert(!requests.some(d => d.positionSource === 'optical'), 'internal mode does not require or probe cDAQ');
  console.log('CONNECTION TESTS PASSED');
})().catch(e => { console.error(e); process.exit(1); });
